    /// <summary>Returns the repository root: the nearest ancestor of the test output directory that holds ViajantesTurismo.slnx.</summary>
    public static string GetRepositoryRoot()
    {
        var currentDirectory = new DirectoryInfo(AppContext.BaseDirectory);

        while (currentDirectory is not null)
        {
            var solutionPath = Path.Combine(currentDirectory.FullName, "ViajantesTurismo.slnx");
            if (File.Exists(solutionPath))
            {
                return currentDirectory.FullName;
            }

            currentDirectory = currentDirectory.Parent;
        }

        throw new InvalidOperationException("Could not locate the repository root from the test output directory.");
    }

    private static bool EnablesProductionHttpAnalyzer(XDocument project)
    {
        return project.Descendants().Any(static element =>
        {
            var itemPath = (element.Attribute("Include")?.Value ?? element.Attribute("Update")?.Value)?.Replace('\\', '/');

            if (string.Equals(element.Name.LocalName, "ProjectReference", StringComparison.OrdinalIgnoreCase))
            {
                var outputItemType = element.Attribute("OutputItemType")?.Value
                    ?? element.Elements().FirstOrDefault(static child => string.Equals(child.Name.LocalName, "OutputItemType", StringComparison.OrdinalIgnoreCase))?.Value;
                return itemPath?.EndsWith("/ViajantesTurismo.Architecture.Analyzers.csproj", StringComparison.OrdinalIgnoreCase) == true
                    && string.Equals(outputItemType, "Analyzer", StringComparison.OrdinalIgnoreCase);
            }

            return string.Equals(element.Name.LocalName, "Analyzer", StringComparison.OrdinalIgnoreCase)
                && itemPath?.Contains("ViajantesTurismo.Architecture.Analyzers", StringComparison.OrdinalIgnoreCase) == true;
        });
    }

    private static IEnumerable<string> EnumerateRepositoryFiles(DirectoryInfo directory, string searchPattern)
    {
        foreach (var file in directory.EnumerateFiles(searchPattern))
        {
            yield return file.FullName;
        }

        foreach (var childDirectory in directory.EnumerateDirectories())
        {
            if (IsIgnoredDirectoryName(childDirectory.Name))
            {
                continue;
            }

            foreach (var file in EnumerateRepositoryFiles(childDirectory, searchPattern))
            {
                yield return file;
            }
        }
    }

    private static bool IsIgnoredDirectoryName(string directoryName)
    {
        return directoryName is "bin" or "obj" or ".git" or ".nuget" or ".worktrees" or ".local";
    }

    private static bool ContainsDirectorySegment(string path, string directoryName)
    {
        return path.Contains(
            $"{Path.DirectorySeparatorChar}{directoryName}{Path.DirectorySeparatorChar}",
            StringComparison.Ordinal);
    }

    private static bool IsDirectiveFor(PragmaWarningDirectiveTriviaSyntax directive, SyntaxKind keyword, string diagnosticId)
    {
        return directive.DisableOrRestoreKeyword.IsKind(keyword)
            && directive.ErrorCodes.Count == 1
            && string.Equals(directive.ErrorCodes[0].ToString(), diagnosticId, StringComparison.Ordinal);
    }

    private static bool IsExactSiteStatement(StatementSyntax statement)
    {
        var descendantNodes = statement.DescendantNodes().ToArray();
        if (descendantNodes.OfType<StatementSyntax>().Any()
            || descendantNodes.Any(static node => node is ConditionalExpressionSyntax
                or SwitchExpressionSyntax
                or ConditionalAccessExpressionSyntax
                || node.IsKind(SyntaxKind.CoalesceExpression)
                || node.IsKind(SyntaxKind.LogicalAndExpression)
                || node.IsKind(SyntaxKind.LogicalOrExpression)))
        {
            return false;
        }

        var invocationSites = descendantNodes.OfType<InvocationExpressionSyntax>().Count();
        var objectCreationSites = descendantNodes.Count(static node => (node is ObjectCreationExpressionSyntax or ImplicitObjectCreationExpressionSyntax)
            && !node.Ancestors().OfType<InvocationExpressionSyntax>().Any());
        var topLevelAssignment = (statement as ExpressionStatementSyntax)?.Expression as AssignmentExpressionSyntax;
        var hasNestedAssignment = descendantNodes
            .OfType<AssignmentExpressionSyntax>()
            .Any(assignment => !ReferenceEquals(assignment, topLevelAssignment));
        var nestedSites = invocationSites + objectCreationSites;
        var eligibleSites = topLevelAssignment is not null && nestedSites <= 1
            ? 1
            : nestedSites;
        var hasTypedAddHttpClientArguments = descendantNodes
            .OfType<InvocationExpressionSyntax>()
            .Any(static invocation =>
            {
                var genericName = invocation.Expression switch
                {
                    MemberAccessExpressionSyntax { Name: GenericNameSyntax memberName } => memberName,
                    GenericNameSyntax directName => directName,
                    _ => null
                };
                return genericName is not null
                    && string.Equals(genericName.Identifier.ValueText, "AddHttpClient", StringComparison.Ordinal)
                    && (genericName.TypeArgumentList.Arguments.Count > 1
                        || invocation.ArgumentList.Arguments.Count > 0);
            });
        if (eligibleSites != 1 || hasNestedAssignment || hasTypedAddHttpClientArguments)
        {
            return false;
        }

        return statement switch
        {
            ExpressionStatementSyntax => true,
            LocalDeclarationStatementSyntax localDeclaration => localDeclaration.Declaration.Variables.Count == 1,
            ReturnStatementSyntax => true,
            _ => false
        };
    }

    private static bool IsSuppressMessageAttribute(
        AttributeSyntax attribute,
        HashSet<string> suppressionAliases,
        SemanticModel semanticModel)
    {
        var attributeName = attribute.Name switch
        {
            IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
            QualifiedNameSyntax qualified => qualified.Right.Identifier.ValueText,
            AliasQualifiedNameSyntax aliasQualified => aliasQualified.Name.Identifier.ValueText,
            _ => attribute.Name.ToString()
        };

        if (suppressionAliases.Contains(attributeName))
        {
            return true;
        }

        var attributeType = (semanticModel.GetSymbolInfo(attribute).Symbol as IMethodSymbol)?.ContainingType
            ?? semanticModel.GetTypeInfo(attribute).Type;
        if (attributeType is not null && attributeType.TypeKind != TypeKind.Error)
        {
            return string.Equals(
                    attributeType.ContainingNamespace.ToDisplayString(),
                    "System.Diagnostics.CodeAnalysis",
                    StringComparison.Ordinal)
                && attributeType.Name is "SuppressMessageAttribute" or "UnconditionalSuppressMessageAttribute";
        }

        var normalizedName = string.Concat(attribute.Name.DescendantTokens().Select(static token => token.Text));
        return normalizedName is
            "System.Diagnostics.CodeAnalysis.SuppressMessage"
            or "System.Diagnostics.CodeAnalysis.SuppressMessageAttribute"
            or "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage"
            or "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute"
            or "global::System.Diagnostics.CodeAnalysis.SuppressMessage"
            or "global::System.Diagnostics.CodeAnalysis.SuppressMessageAttribute"
            or "global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage"
            or "global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute";
    }

    private static bool IsSuppressMessageNamespaceImportDirective(UsingDirectiveSyntax directive)
    {
        if (directive.Name is null)
        {
            return false;
        }

        var normalizedName = string.Concat(directive.Name.DescendantTokens().Select(static token => token.Text));
        return normalizedName is
            "System.Diagnostics.CodeAnalysis"
            or "global::System.Diagnostics.CodeAnalysis";
    }

    private static bool IsUnqualifiedSuppressMessageAttribute(AttributeSyntax attribute)
    {
        var normalizedName = string.Concat(attribute.Name.DescendantTokens().Select(static token => token.Text));
        return normalizedName is
            "SuppressMessage"
            or "SuppressMessageAttribute"
            or "UnconditionalSuppressMessage"
            or "UnconditionalSuppressMessageAttribute";
    }

    private static bool IsNamespaceAliasSuppressMessageAttribute(
        AttributeSyntax attribute,
        HashSet<string> frameworkNamespaceAliases)
    {
        return attribute.Name is AliasQualifiedNameSyntax aliasQualified
            && frameworkNamespaceAliases.Contains(aliasQualified.Alias.Identifier.ValueText)
            && aliasQualified.Name.Identifier.ValueText is
                "SuppressMessage"
                or "SuppressMessageAttribute"
                or "UnconditionalSuppressMessage"
                or "UnconditionalSuppressMessageAttribute";
    }

    private static bool ContainsGeneratedCodeAttribute(string source)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source, RepositoryParseOptions);
        var root = syntaxTree.GetRoot();
        var generatedCodeAliases = root.DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .Where(static directive => directive.Alias is not null && directive.Name is not null)
            .Where(static directive => IsGeneratedCodeAttributeName(
                string.Concat(directive.Name!.DescendantTokens().Select(static token => token.Text))))
            .Select(static directive => directive.Alias?.Name.Identifier.ValueText)
            .OfType<string>()
            .ToHashSet(StringComparer.Ordinal);

        return root
            .DescendantNodes()
            .OfType<AttributeSyntax>()
            .Any(attribute =>
            {
                var normalizedName = string.Concat(attribute.Name.DescendantTokens().Select(static token => token.Text));
                return IsGeneratedCodeAttributeName(normalizedName)
                    || generatedCodeAliases.Contains(normalizedName);
            });
    }

    private static bool IsGeneratedCodeAttributeName(string normalizedName)
    {
        return normalizedName is
            "GeneratedCode"
            or "GeneratedCodeAttribute"
            or "System.CodeDom.Compiler.GeneratedCode"
            or "System.CodeDom.Compiler.GeneratedCodeAttribute"
            or "global::System.CodeDom.Compiler.GeneratedCode"
            or "global::System.CodeDom.Compiler.GeneratedCodeAttribute";
    }

    private static bool IsSuppressMessageAliasDirective(UsingDirectiveSyntax directive)
    {
        if (directive.Alias is null || directive.Name is null)
        {
            return false;
        }

        var normalizedName = string.Concat(directive.Name.DescendantTokens().Select(static token => token.Text));
        return normalizedName is
            "System.Diagnostics.CodeAnalysis.SuppressMessageAttribute"
            or "global::System.Diagnostics.CodeAnalysis.SuppressMessageAttribute"
            or "System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute"
            or "global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessageAttribute";
    }

    private static bool ContainsProductionHttpPragmaDisableInAnyBranch(string source)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source, RepositoryParseOptions);
        var root = syntaxTree.GetRoot();
        if (root.DescendantTrivia(descendIntoTrivia: true)
            .Select(static trivia => trivia.GetStructure())
            .OfType<PragmaWarningDirectiveTriviaSyntax>()
            .Any(static directive => directive.DisableOrRestoreKeyword.IsKind(SyntaxKind.DisableKeyword)
                && directive.ErrorCodes.Any(static code => string.Equals(code.ToString(), ProductionApiHttpDiagnosticId, StringComparison.Ordinal))))
        {
            return true;
        }

        return root.DescendantTrivia(descendIntoTrivia: true)
            .Where(static trivia => trivia.IsKind(SyntaxKind.DisabledTextTrivia))
            .Any(static trivia => ContainsProductionHttpPragmaDisableInAnyBranch(trivia.ToString()));
    }

    private static bool ContainsProductionHttpSuppressionInAnyBranch(string source)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(source, RepositoryParseOptions);
        var root = syntaxTree.GetRoot();
        var usingDirectives = root.DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .ToArray();
        if (usingDirectives.Any(static directive =>
            directive.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword)
            && (IsSuppressMessageAliasDirective(directive)
                || IsSuppressMessageNamespaceImportDirective(directive))))
        {
            return true;
        }

        var aliases = usingDirectives
            .Where(static directive => IsSuppressMessageAliasDirective(directive))
            .Select(static directive => directive.Alias?.Name.Identifier.ValueText)
            .OfType<string>()
            .ToHashSet(StringComparer.Ordinal);

        var semanticModel = CSharpCompilation.Create(
            "AnalyzerSuppressionPolicyConditional",
            [syntaxTree],
            [CoreLibraryReference]).GetSemanticModel(syntaxTree);
        if (root.DescendantNodes()
            .OfType<AttributeSyntax>()
            .Any(attribute => IsSuppressMessageAttribute(attribute, aliases, semanticModel)
                && SuppressesProductionHttpOrHasUnresolvedCheckId(attribute, semanticModel)))
        {
            return true;
        }

        return root.DescendantTrivia(descendIntoTrivia: true)
            .Where(static trivia => trivia.IsKind(SyntaxKind.DisabledTextTrivia))
            .Any(static trivia => ContainsProductionHttpSuppressionInAnyBranch(trivia.ToString()));
    }

    private static bool SuppressesProductionHttpOrHasUnresolvedCheckId(
        AttributeSyntax attribute,
        SemanticModel semanticModel)
    {
        if (attribute.ArgumentList is not { } argumentList)
        {
            return false;
        }

        var arguments = argumentList.Arguments;
        var checkIdArgument = arguments.FirstOrDefault(argument =>
                semanticModel.GetOperation(argument) is IArgumentOperation { Parameter.Name: var parameterName }
                && string.Equals(parameterName, "checkId", StringComparison.OrdinalIgnoreCase))
            ?? arguments.FirstOrDefault(static argument =>
                string.Equals(argument.NameColon?.Name.Identifier.ValueText, "checkId", StringComparison.OrdinalIgnoreCase)
                || string.Equals(argument.NameEquals?.Name.Identifier.ValueText, "CheckId", StringComparison.OrdinalIgnoreCase))
            ?? arguments
                .Where(static argument => argument.NameEquals is null)
                .Skip(1)
                .FirstOrDefault();
        if (checkIdArgument is null)
        {
            return false;
        }

        var constantValue = semanticModel.GetConstantValue(checkIdArgument.Expression);
        if (!constantValue.HasValue || constantValue.Value is not string value)
        {
            return true;
        }

        return string.Equals(value, ProductionApiHttpDiagnosticId, StringComparison.OrdinalIgnoreCase)
            || value.StartsWith(ProductionApiHttpDiagnosticId + ":", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsBroadAnalyzerConfigSuppression(string setting, string? currentSection)
    {
        var separatorIndex = setting.IndexOf('=', StringComparison.Ordinal);
        if (separatorIndex < 0)
        {
            return false;
        }

        var key = setting.Substring(0, separatorIndex);
        var value = setting.Substring(separatorIndex + 1);
        if (string.Equals(key, "generated_code", StringComparison.OrdinalIgnoreCase)
            && string.Equals(value, "true", StringComparison.OrdinalIgnoreCase))
        {
            return !string.Equals(currentSection, ApprovedGeneratedCodeSection, StringComparison.Ordinal);
        }

        var suppressesDiagnostics = string.Equals(value, "none", StringComparison.OrdinalIgnoreCase)
            || string.Equals(value, "silent", StringComparison.OrdinalIgnoreCase)
            || string.Equals(value, "suggestion", StringComparison.OrdinalIgnoreCase);

        return suppressesDiagnostics
            && (string.Equals(key, $"dotnet_diagnostic.{ProductionApiHttpDiagnosticId}.severity", StringComparison.OrdinalIgnoreCase)
                || string.Equals(key, "dotnet_analyzer_diagnostic.category-Architecture.severity", StringComparison.OrdinalIgnoreCase)
                || string.Equals(key, "dotnet_analyzer_diagnostic.severity", StringComparison.OrdinalIgnoreCase));
    }

    private static bool HasJustification(SyntaxTree syntaxTree, PragmaWarningDirectiveTriviaSyntax directive)
    {
        const string justificationMarker = "// Justification:";
        var sourceLine = syntaxTree.GetText().Lines.GetLineFromPosition(directive.SpanStart).ToString();
        var markerIndex = sourceLine.IndexOf(justificationMarker, StringComparison.Ordinal);

        return markerIndex >= 0
            && sourceLine[(markerIndex + justificationMarker.Length)..].Trim().Length >= 12;
    }

    private static IEnumerable<string> FindNoWarnDiagnosticEntries(string text)
    {
        if (!text.TrimStart().StartsWith('<'))
        {
            return [];
        }

        return FindNoWarnDiagnosticEntries(XDocument.Parse(text));
    }

    private static IEnumerable<string> FindNoWarnDiagnosticEntries(XDocument project)
    {
        return project.Descendants()
            .Where(static element => string.Equals(element.Name.LocalName, "NoWarn", StringComparison.OrdinalIgnoreCase))
            .SelectMany(static element => element.Value
                .Replace("$(NoWarn)", string.Empty, StringComparison.Ordinal)
                .Split([';', ','], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries));
    }

    private static IEnumerable<string> FindForbiddenAnalyzerPolicyInputs(string text, string displayPath)
    {
        if (!text.TrimStart().StartsWith('<'))
        {
            return [];
        }

        var project = XDocument.Parse(text);
        return project.Root?.DescendantsAndSelf()
            .Where(static element =>
                ((string.Equals(element.Name.LocalName, "GlobalAnalyzerConfigFiles", StringComparison.OrdinalIgnoreCase)
                        || string.Equals(element.Name.LocalName, "EditorConfigFiles", StringComparison.OrdinalIgnoreCase))
                    && element.Attributes().Any(static attribute =>
                        (string.Equals(attribute.Name.LocalName, "Include", StringComparison.OrdinalIgnoreCase)
                            || string.Equals(attribute.Name.LocalName, "Update", StringComparison.OrdinalIgnoreCase))
                        && !string.IsNullOrWhiteSpace(attribute.Value)))
                || (string.Equals(element.Name.LocalName, "CodeAnalysisRuleSet", StringComparison.OrdinalIgnoreCase)
                    && !string.IsNullOrWhiteSpace(element.Value))
                || (string.Equals(element.Name.LocalName, "WarningsNotAsErrors", StringComparison.OrdinalIgnoreCase)
                    && !string.IsNullOrWhiteSpace(element.Value))
                || ((string.Equals(element.Name.LocalName, "RunAnalyzers", StringComparison.OrdinalIgnoreCase)
                        || string.Equals(element.Name.LocalName, "RunAnalyzersDuringBuild", StringComparison.OrdinalIgnoreCase)
                        || string.Equals(element.Name.LocalName, "TreatWarningsAsErrors", StringComparison.OrdinalIgnoreCase))
                    && !string.Equals(element.Value.Trim(), "true", StringComparison.OrdinalIgnoreCase)))
            .Select(element => $"{displayPath}:{element.Name.LocalName}")
            ?? [];
    }
