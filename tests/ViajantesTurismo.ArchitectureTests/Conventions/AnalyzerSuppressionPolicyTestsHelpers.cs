    /// <summary>Reports whether the path is inside bin, obj, .git or .nuget, or is a feature-file code-behind.</summary>
    public static bool IsIgnoredPath(string path)
    {
        return ContainsDirectorySegment(path, "bin")
            || ContainsDirectorySegment(path, "obj")
            || ContainsDirectorySegment(path, ".git")
            || ContainsDirectorySegment(path, ".nuget")
            || path.EndsWith(".feature.cs", StringComparison.Ordinal);
    }

    /// <summary>Reports whether the path is a migration designer or model snapshot file.</summary>
    public static bool IsGeneratedSource(string repositoryRoot, string path)
    {
        var relativePath = Path.GetRelativePath(repositoryRoot, path).Replace('\\', '/');

        return relativePath.Contains("/Migrations/", StringComparison.Ordinal)
            && (relativePath.EndsWith(".Designer.cs", StringComparison.Ordinal)
                || relativePath.EndsWith("ModelSnapshot.cs", StringComparison.Ordinal));
    }

    /// <summary>Reports whether an Api service source file is generated and therefore not an approved production API source.</summary>
    public static bool IsUnapprovedProductionApiGeneratedSource(string relativePath, string source)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(relativePath);
        ArgumentNullException.ThrowIfNull(source);

        var normalizedPath = relativePath.Replace('\\', '/');
        if (!normalizedPath.StartsWith("src/", StringComparison.Ordinal)
            || !normalizedPath.Contains(".ApiService/", StringComparison.Ordinal))
        {
            return false;
        }

        var fileName = Path.GetFileName(normalizedPath);
        return fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            || source.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
            || source.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase)
            || ContainsGeneratedCodeAttribute(source);
    }

    /// <summary>Reports whether the source uses the framework SuppressMessage attribute, including via aliases, global usings or disabled branches.</summary>
    public static bool ContainsFrameworkSuppressMessageAttribute(string source)
    {
        ArgumentNullException.ThrowIfNull(source);

        var syntaxTree = CSharpSyntaxTree.ParseText(source, RepositoryParseOptions);
        var root = syntaxTree.GetRoot();
        var usingDirectives = root.DescendantNodes()
            .OfType<UsingDirectiveSyntax>()
            .ToArray();
        if (usingDirectives.Any(static directive =>
            directive.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword)
            && (IsSuppressMessageAliasDirective(directive)
                || IsSuppressMessageNamespaceImportDirective(directive))))
        {
            return true;
        }

        var aliases = usingDirectives
            .Where(static directive => IsSuppressMessageAliasDirective(directive))
            .Select(static directive => directive.Alias?.Name.Identifier.ValueText)
            .OfType<string>()
            .ToHashSet(StringComparer.Ordinal);
        var importsFrameworkNamespace = usingDirectives.Any(static directive =>
            directive.Alias is null && IsSuppressMessageNamespaceImportDirective(directive));
        var frameworkNamespaceAliases = usingDirectives
            .Where(static directive => directive.Alias is not null && IsSuppressMessageNamespaceImportDirective(directive))
            .Select(static directive => directive.Alias?.Name.Identifier.ValueText)
            .OfType<string>()
            .ToHashSet(StringComparer.Ordinal);
        var semanticModel = CSharpCompilation.Create(
            "AnalyzerSuppressionPolicyRepository",
            [syntaxTree],
            [CoreLibraryReference]).GetSemanticModel(syntaxTree);

        var containsActiveSuppression = root.DescendantNodes()
            .OfType<AttributeSyntax>()
            .Any(attribute => IsSuppressMessageAttribute(attribute, aliases, semanticModel)
                || (importsFrameworkNamespace && IsUnqualifiedSuppressMessageAttribute(attribute))
                || IsNamespaceAliasSuppressMessageAttribute(attribute, frameworkNamespaceAliases));
        return containsActiveSuppression
            || root.DescendantTrivia(descendIntoTrivia: true)
                .Where(static trivia => trivia.IsKind(SyntaxKind.DisabledTextTrivia))
                .Any(static trivia => ContainsFrameworkSuppressMessageAttribute(trivia.ToString()));
    }

