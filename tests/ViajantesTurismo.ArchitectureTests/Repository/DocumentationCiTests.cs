using System.Text.Json;

using SharedKernel.Testing;

namespace ViajantesTurismo.ArchitectureTests.Repository;

[Trait(TestTraitNames.CategoryName, TestTraits.CommandLineCategory)]
public sealed class DocumentationCiTests
{
    [Theory]
    [InlineData("docs/architecture/generated-diagrams.json")]
    [InlineData("docs/architecture/mediator-topology.json")]
    [InlineData("docs/generated-tables-of-contents.json")]
    public void Generated_documents_name_the_pinned_tool_in_their_refresh_command(string configPath)
    {
        // Arrange
        const string manifestPath = ".config/dotnet-tools.json";
        var root = RepositoryRoot.Locate("ViajantesTurismo.slnx");
        using var manifest = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, manifestPath)));
        using var config = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, configPath)));
        var pinnedCommand = manifest.RootElement.GetProperty("tools")
            .GetProperty("pandabear.sharedkernel.documentation.tool").GetProperty("commands")
            .EnumerateArray().ShouldHaveSingleItem().GetString().ShouldNotBeNull();
        var generatorName = config.RootElement.GetProperty("generatorName").GetString().ShouldNotBeNull();
        var docsPath = config.RootElement.GetProperty("docsPath").GetString().ShouldNotBeNull();

        // Act
        var targetPaths = config.RootElement.GetProperty("blocks").EnumerateArray()
            .Select(block => block.GetProperty("targetPath").GetString().ShouldNotBeNull())
            .Distinct(StringComparer.Ordinal).ToArray();

        // Assert
        generatorName.ShouldBe("sharedkernel-docs");
        foreach (var targetPath in targetPaths)
        {
            var document = File.ReadAllText(Path.Combine(root, docsPath, targetPath));
            document.ShouldContain($"`dotnet {pinnedCommand} generate --config {configPath}`", StringComparison.Ordinal);
            document.ShouldContain($"<!-- Generated by {generatorName}. Do not edit by hand. -->", StringComparison.Ordinal);
        }
    }

    [Fact]
    public void Documentation_workflow_avoids_hidden_test_runs_and_lints_every_change_alike()
    {
        // Arrange
        var root = RepositoryRoot.Locate("ViajantesTurismo.slnx");
        var workflow = File.ReadAllText(Path.Combine(root, ".github/workflows/ci.yml"));

        // Act
        var detection = workflow.Split("  detect-changes:", StringSplitOptions.None)[1]
            .Split("\n  calculate-version:", StringSplitOptions.None)[0];
        var version = workflow.Split("  calculate-version:", StringSplitOptions.None)[1]
            .Split("\n  test-slices:", StringSplitOptions.None)[0];
        var lint = workflow.Split("  lint:", StringSplitOptions.None)[1];
        var slices = workflow.Split("  test-slices:", StringSplitOptions.None)[1]
            .Split("\n  build-and-test:", StringSplitOptions.None)[0];

        // Assert
        detection.ShouldNotContain("setup-ci-prerequisites", StringComparison.Ordinal);
        detection.ShouldContain("pull_request) BASE_SHA=\"$(git rev-parse HEAD^1)\" ;;", StringComparison.Ordinal);
        detection.ShouldContain("push) BASE_SHA=\"$PUSH_BEFORE\" ;;", StringComparison.Ordinal);
        detection.ShouldContain("merge_group) BASE_SHA=\"$MERGE_GROUP_BASE\" ;;", StringComparison.Ordinal);
        detection.ShouldContain("PUSH_BEFORE: ${{ github.event.before }}", StringComparison.Ordinal);
        detection.ShouldContain("MERGE_GROUP_BASE: ${{ github.event.merge_group.base_sha }}", StringComparison.Ordinal);
        detection.ShouldContain("select --base \"$BASE_SHA\" --github-output \"$GITHUB_OUTPUT\"", StringComparison.Ordinal);
        version.ShouldContain("needs: detect-changes", StringComparison.Ordinal);
        version.ShouldContain("needs.detect-changes.outputs.build_required == 'true'", StringComparison.Ordinal);
        lint.ShouldNotContain("documentation_only", StringComparison.Ordinal);
        lint.ShouldNotContain("python3", StringComparison.Ordinal);
        lint.ShouldNotContain("scripts/lint-", StringComparison.Ordinal);
        lint.ShouldContain("- name: Set up CI prerequisites\n        uses: ./.github/actions/setup-ci-prerequisites", StringComparison.Ordinal);
        lint.ShouldContain("sudo apt-get install --yes shellcheck", StringComparison.Ordinal);
        lint.ShouldContain("run: shellcheck -- .devcontainer/*.sh scripts/*.sh setup-dev.sh", StringComparison.Ordinal);
        foreach (var check in (string[])["verify-text-encoding", "verify-line-endings", "verify-json", "verify-links", "verify-gherkin", "verify"])
        {
            lint.ShouldContain($"dotnet repo {check} --root .", StringComparison.Ordinal);
        }

        lint.ShouldContain("dotnet repo verify-test-taxonomy --root . --report", StringComparison.Ordinal);
        lint.ShouldContain("dotnet docs verify --config docs/architecture/generated-diagrams.json", StringComparison.Ordinal);
        lint.ShouldContain("dotnet docs verify --config docs/generated-tables-of-contents.json", StringComparison.Ordinal);
        lint.ShouldContain("dotnet docs check --config docs/architecture/documentation-conformance.json", StringComparison.Ordinal);
        const string restoreTopology = "dotnet restore src/ViajantesTurismo.Admin.Api --locked-mode";
        const string emitTopology = "dotnet build src/ViajantesTurismo.Admin.Api -c Release --no-restore -p:GenerateMediatorTopology=true";
        const string verifyTopology = "dotnet docs verify --config docs/architecture/mediator-topology.json";
        lint.ShouldContain(restoreTopology, StringComparison.Ordinal);
        lint.ShouldContain(emitTopology, StringComparison.Ordinal);
        lint.ShouldContain(verifyTopology, StringComparison.Ordinal);
        lint.IndexOf(restoreTopology, StringComparison.Ordinal).ShouldBeLessThan(lint.IndexOf(emitTopology, StringComparison.Ordinal));
        lint.IndexOf(emitTopology, StringComparison.Ordinal).ShouldBeLessThan(lint.IndexOf(verifyTopology, StringComparison.Ordinal));
        lint.ShouldContain("uses: tj-actions/changed-files@", StringComparison.Ordinal);
        lint.ShouldContain("uses: DavidAnson/markdownlint-cli2-action@", StringComparison.Ordinal);
        slices.ShouldContain("needs.detect-changes.outputs.build_required == 'true'", StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("true", "success", "success", "success", 0)]
    [InlineData("true", "failure", "success", "success", 1)]
    [InlineData("true", "success", "failure", "success", 1)]
    [InlineData("true", "success", "success", "failure", 1)]
    [InlineData("true", "success", "success", "skipped", 1)]
    [InlineData("false", "skipped", "skipped", "skipped", 0)]
    [InlineData("false", "failure", "skipped", "skipped", 1)]
    [InlineData("false", "skipped", "skipped", "failure", 1)]
    [InlineData("", "skipped", "skipped", "skipped", 1)]
    public async Task Quality_gate_accepts_documentation_skips_but_rejects_failures_and_missing_selection(
        string required, string tests, string build, string format, int expected)
    {
        // Arrange
        var root = RepositoryRoot.Locate("ViajantesTurismo.slnx");
        var workflow = await File.ReadAllTextAsync(Path.Combine(root, ".github/workflows/ci.yml"), TestContext.Current.CancellationToken);
        var step = workflow.Split("      - name: Require successful change selection and tests\n", StringSplitOptions.None)[1]
            .Split("      - name: Checkout repository", StringSplitOptions.None)[0];
        var script = step.Split("        run: |\n", StringSplitOptions.None)[1];
        using var workspace = new TemporaryWorkspace();
        workspace.WriteFile("gate.sh", "set -e\n" + script);

        // Act
        var result = await TestProcess.Run("bash", workspace.RootPath, ["gate.sh"],
            TestContext.Current.CancellationToken, new Dictionary<string, string?>
            {
                ["SELECTION_RESULT"] = "success",
                ["TEST_RESULT"] = tests,
                ["BUILD_RESULT"] = build,
                ["FORMAT_RESULT"] = format,
                ["BUILD_REQUIRED"] = required
            });

        // Assert
        result.ExitCode.ShouldBe(expected);
    }
}
